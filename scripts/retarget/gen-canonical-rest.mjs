#!/usr/bin/env node
/**
 * Writes src/engine/retarget/CanonicalRest.generated.ts: the rest LOCAL
 * rotation of every humanoid-mapped joint of public/models/BANNON_rigged.glb.
 *
 * The runtime uses it to decide, WITHOUT fetching the canonical GLB, whether a
 * fighter's rig is the same skeleton the baked bank was authored on (then the
 * clips play untouched) or a different one (then they are retargeted).
 *
 *   node --experimental-strip-types --import ./scripts/register-ts-resolve.mjs scripts/retarget/gen-canonical-rest.mjs
 */
import { writeFileSync } from 'node:fs';
import { loadGlbNode } from './load-glb-node.mjs';
import { buildRetargetRig } from '../../src/engine/retarget/UniversalRetarget.ts';
import { mappedJointNames } from '../../src/engine/retarget/HumanoidBoneMap.ts';

const g = await loadGlbNode('public/models/BANNON_rigged.glb');
const rig = buildRetargetRig(g.scene, { label: 'canonical', file: 'BANNON_rigged.glb' });
const out = {};
for (const name of mappedJointNames(rig.map).filter((n) => !/Hand(Thumb|Index|Middle|Ring|Pinky)/.test(n))) {
  const q = rig.restLocal.get(rig.byName.get(name)).q;
  out[name] = q.toArray().map((v) => Math.round(v * 1e6) / 1e6);
}
const body = `// GENERATED by scripts/retarget/gen-canonical-rest.mjs from public/models/BANNON_rigged.glb — do not edit.
/** Rest local rotation [x, y, z, w] of each humanoid-mapped canonical joint (sanitized names). */
export const CANONICAL_REST_LOCAL: Readonly<Record<string, readonly [number, number, number, number]>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync('src/engine/retarget/CanonicalRest.generated.ts', body);
console.log(`wrote ${Object.keys(out).length} joints`);
