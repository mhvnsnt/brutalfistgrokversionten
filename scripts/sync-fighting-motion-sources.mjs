#!/usr/bin/env node
/**
 * Discovers animation-bearing assets from the authorized Tekken 3 Recompiled
 * and Schwarzer Blitz source repositories when those repositories are present
 * in the checkout/build environment.
 *
 * This is an import manifest, not a clip generator: only files that actually
 * exist in the source checkout are indexed. Native Bannon GLB clips remain the
 * preferred runtime bank; external source formats are kept available for a
 * later conversion/import step rather than being silently replaced.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const sourceRoots = [
  {
    id: 'tekken3-recompiled',
    candidates: [
      path.join(root, 'vendor', 'BrutalfistbaseofTekken3Recompiled'),
      path.join(root, 'vendor', 'tekken3-recompiled'),
    ],
  },
  {
    id: 'schwarzer-blitz',
    candidates: [
      path.join(root, 'vendor', 'SchwarzerblitzEngine'),
      path.join(root, 'vendor', 'schwarzer-blitz'),
    ],
  },
];

// Includes common skeletal/animation containers used by the two source
// families. .x matters for Schwarzer Blitz: its engine's documented skeletal
// mesh format is DirectX .x, where animation keys may live with the skeleton.
const supported = new Set([
  '.glb', '.gltf', '.fbx', '.bvh', '.anim', '.json',
  '.x', '.dae', '.smd', '.dmx', '.md5anim', '.vmd', '.b3d',
]);
const ignored = new Set(['node_modules', '.git', 'dist', '.next', '.cache']);

const animationHints = [
  'anim', 'animation', 'motion', 'move', 'moves', 'clip', 'clips',
  'fight', 'combat', 'attack', 'throw', 'grapple', 'stance', 'idle',
  'walk', 'run', 'dash', 'guard', 'block', 'hit', 'fall', 'getup',
  'victory', 'defeat', 'intro', 'special', 'reversal', 'parry',
];

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ignored.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (supported.has(path.extname(entry.name).toLowerCase())) out.push(full);
  }
  return out;
}

function findRoot(candidates) {
  return candidates.find((candidate) => fs.existsSync(candidate));
}

function looksAnimationBearing(relativePath, extension) {
  if (['.bvh', '.anim', '.md5anim', '.vmd', '.smd', '.dmx'].includes(extension)) return true;
  const normalized = relativePath.toLowerCase();
  return animationHints.some((hint) => normalized.includes(hint));
}

const records = [];
for (const source of sourceRoots) {
  const sourceRoot = findRoot(source.candidates);
  if (!sourceRoot) continue;
  for (const file of walk(sourceRoot)) {
    const relative = path.relative(sourceRoot, file).replaceAll(path.sep, '/');
    const extension = path.extname(file).toLowerCase();
    records.push({
      source: source.id,
      path: relative,
      extension: extension.slice(1),
      name: path.basename(file, extension),
      animationBearing: looksAnimationBearing(relative, extension),
    });
  }
}

records.sort((a, b) => `${a.source}/${a.path}`.localeCompare(`${b.source}/${b.path}`));

const animationRecords = records.filter((record) => record.animationBearing);
const output = path.join(root, 'src', 'generated', 'FightingMotionSources.generated.ts');
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(
  output,
  `// Generated by scripts/sync-fighting-motion-sources.mjs.\n` +
  `// Contains only assets actually present in the authorized source checkout.\n` +
  `export const IMPORTED_FIGHTING_MOTION_SOURCES = ${JSON.stringify(records, null, 2)} as const;\n` +
  `export const IMPORTED_FIGHTING_ANIMATION_SOURCES = ${JSON.stringify(animationRecords, null, 2)} as const;\n`,
);

console.log(`Fighting source scan: ${records.length} real supported source files indexed.`);
console.log(`Animation-bearing source files: ${animationRecords.length}.`);
for (const source of sourceRoots) {
  const count = records.filter((record) => record.source === source.id).length;
  const animationCount = animationRecords.filter((record) => record.source === source.id).length;
  console.log(`  ${source.id}: ${count} supported / ${animationCount} animation-bearing`);
}
