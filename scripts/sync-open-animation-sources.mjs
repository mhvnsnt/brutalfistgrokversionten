#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

export const OPEN_ANIMATION_SOURCES = [
  { id:'quaternius-ual-1', root:'vendor/quaternius-ual-1', license:'CC0-1.0', url:'https://quaternius.itch.io/universal-animation-library' },
  { id:'quaternius-ual-2', root:'vendor/quaternius-ual-2', license:'CC0-1.0', url:'https://quaternius.itch.io/universal-animation-library-2' },
];
const supported = new Set(['.glb','.gltf','.fbx','.bvh','.blend','.dae','.anim']);
const ignored = new Set(['node_modules','.git','dist','.next','.cache']);

export function inferMotionRoles(filePath) {
  const name=filePath.toLowerCase().replace(/[_-]+/g,' ');
  const roles=[];
  const add=(role,...terms)=>{if(terms.some(term=>name.includes(term))) roles.push(role);};
  add('idle','idle','stand');
  add('walk_forward','walk forward','walkforward','forward walk');
  add('walk_back','walk backward','walkback','backward walk');
  add('strafe_left','strafe left','left strafe');
  add('strafe_right','strafe right','right strafe');
  add('dash','dash','sprint','run');
  add('jump','jump','leap');
  add('fall','fall','land');
  add('attack','punch','kick','strike','attack','combo','melee');
  add('defense','block','guard','parry','dodge','evade');
  add('hit_reaction','hit','hurt','damage','reaction');
  add('knockdown','knockdown','knock down','death');
  add('getup','getup','get up','recover');
  add('throw','throw','grapple','takedown','slam');
  return [...new Set(roles)];
}
function walk(dir,out=[]) {
  if(!fs.existsSync(dir)) return out;
  for(const entry of fs.readdirSync(dir,{withFileTypes:true})) {
    if(ignored.has(entry.name)) continue;
    const full=path.join(dir,entry.name);
    if(entry.isDirectory()) walk(full,out);
    else if(supported.has(path.extname(entry.name).toLowerCase())) out.push(full);
  }
  return out;
}
const root=process.cwd(), records=[];
for(const source of OPEN_ANIMATION_SOURCES) {
  const sourceRoot=path.join(root,source.root);
  if(!fs.existsSync(sourceRoot)) continue;
  for(const file of walk(sourceRoot)) {
    const relative=path.relative(sourceRoot,file).replaceAll(path.sep,'/');
    const extension=path.extname(relative).toLowerCase();
    records.push({source:source.id,license:source.license,url:source.url,path:relative,extension:extension.slice(1),name:path.basename(relative,extension),roles:inferMotionRoles(relative)});
  }
}
records.sort((a,b)=>`${a.source}/${a.path}`.localeCompare(`${b.source}/${b.path}`));
const output=path.join(root,'src','generated','OpenAnimationSources.generated.ts');
fs.mkdirSync(path.dirname(output),{recursive:true});
fs.writeFileSync(output,'// Generated by scripts/sync-open-animation-sources.mjs.\n// Only files physically present under vendor/ are listed.\n'+`export const OPEN_ANIMATION_SOURCE_FILES = ${JSON.stringify(records,null,2)} as const;\n`);
console.log(`Open animation source scan: ${records.length} real files indexed.`);
for(const source of OPEN_ANIMATION_SOURCES) console.log(`  ${source.id}: ${records.filter(r=>r.source===source.id).length} supported files`);
